#!/usr/bin/env python3
"""Append verified local observations and refresh bounded persistent context.

--lesson FILE appends a manual record with id,status,evidence,cause,action.
--refresh rebuilds the workspace LEARNINGS.md. Neither action runs a bot.
"""
import argparse
import fcntl
import json
import math
import os
import pathlib
import re
import tempfile
from datetime import datetime, timezone

ROOT = pathlib.Path(__file__).resolve().parents[1]
WORKSPACE = ROOT.parent
RUNTIME = ROOT / ".runtime-odysseus"
LEDGER = ROOT / "docs" / "lessons.jsonl"
OUTPUT = WORKSPACE / "LEARNINGS.md"
MARKER = "<!-- generated by bot-starter/tools/update_learning.py -->"
STATUSES = {"UNVALIDATED", "REJECTED", "PROMISING"}
LESSON_STATUSES = STATUSES | {"confirmed", "inconclusive", "fixed", "blocked"}
LIMIT = 64 * 1024 * 1024


def read_json(path):
    path = pathlib.Path(path)
    if path.stat().st_size > LIMIT:
        raise ValueError("JSON file exceeds size limit")
    value = json.loads(path.read_text())
    if not isinstance(value, dict):
        raise ValueError("Expected JSON object")
    return value


def safe_text(value, label):
    if not isinstance(value, str) or not value.strip() or len(value) > 4000:
        raise ValueError(f"{label} must be nonempty text under 4001 characters")
    if re.search(r"eyJ[A-Za-z0-9_-]{15,}\.[A-Za-z0-9_-]{15,}|BOT_TOKEN\s*=|BEGIN .*PRIVATE KEY", value):
        raise ValueError(f"{label} appears to contain credential material")
    return value.strip()


def validate_lesson(value, root=ROOT, workspace=WORKSPACE):
    if not isinstance(value, dict):
        raise ValueError("Lesson must be an object")
    allowed = {"id", "status", "evidence", "cause", "action"}
    if set(value) != allowed:
        raise ValueError("Lesson requires exactly id,status,evidence,cause,action")
    ident = safe_text(value["id"], "id")
    if not re.fullmatch(r"[A-Za-z0-9_.-]{1,100}", ident):
        raise ValueError("Lesson id must be short and filename-safe")
    if value["status"] not in LESSON_STATUSES:
        raise ValueError("Unsupported manual lesson status")
    evidence = value["evidence"]
    if not isinstance(evidence, list) or not evidence or len(evidence) > 20:
        raise ValueError("evidence must contain 1–20 existing local paths")
    paths = []
    for raw in evidence:
        raw = safe_text(raw, "evidence")
        path = pathlib.Path(raw)
        if not path.is_absolute():
            path = pathlib.Path(root) / path
        path = path.resolve()
        if not path.is_relative_to(pathlib.Path(workspace).resolve()) or not path.is_file():
            raise ValueError("Evidence must be an existing file in this workspace")
        if any(part.startswith(".env") or "token" in part.lower() or
               "credential" in part.lower() for part in path.parts):
            raise ValueError("Credential-related evidence paths are not accepted")
        # Resolve symlinks first; store stable workspace-relative links, not file contents.
        paths.append(str(path.relative_to(pathlib.Path(workspace).resolve())))
    return {"id": ident, "status": value["status"], "evidence": sorted(set(paths)),
            "cause": safe_text(value["cause"], "cause"), "action": safe_text(value["action"], "action")}


def read_ledger(path):
    path = pathlib.Path(path)
    if not path.exists():
        return []
    if path.stat().st_size > LIMIT:
        raise ValueError("Lesson ledger exceeds size limit")
    rows = [json.loads(line) for line in path.read_text().splitlines() if line.strip()]
    if len({row["id"] for row in rows}) != len(rows):
        raise ValueError("Duplicate ids in existing ledger; refusing to rewrite it")
    return rows


def append_lesson(value, ledger=LEDGER, root=ROOT, workspace=WORKSPACE):
    normalized = validate_lesson(value, root, workspace)
    ledger = pathlib.Path(ledger)
    ledger.parent.mkdir(parents=True, exist_ok=True)
    with ledger.open("a+") as handle:
        fcntl.flock(handle, fcntl.LOCK_EX)
        handle.seek(0)
        rows = [json.loads(line) for line in handle if line.strip()]
        for row in rows:
            if row["id"] == normalized["id"]:
                if {key: row[key] for key in normalized} != normalized:
                    raise ValueError("Lesson id already exists with different content; append a new id")
                return False
        record = {**normalized, "recordedAt": datetime.now(timezone.utc).isoformat()}
        handle.seek(0, os.SEEK_END)
        handle.write(json.dumps(record, sort_keys=True, allow_nan=False) + "\n")
        handle.flush()
        os.fsync(handle.fileno())
    return True


def interval(value):
    if (isinstance(value, list) and len(value) == 2 and
        all(type(x) in (int, float) and math.isfinite(x) for x in value) and value[0] <= value[1]):
        return value
    return None


def triage(metrics, reactive=False):
    score = interval(metrics.get("scoreConditional95"))
    win = interval(metrics.get("winPPConditional95" if reactive else "surrogateConditional95"))
    place = interval(metrics.get("placeConditional95")) if reactive else None
    discordant = metrics.get("winGained", metrics.get("exceedanceGainedGames", 0)) + metrics.get(
        "winLost", metrics.get("exceedanceLostGames", 0))
    exact = metrics.get("exactDiscordanceP")
    # Conservative labels organize follow-up; they are not hypothesis-test decisions.
    if score and win and score[1] < 0 and win[1] <= 0 and (not reactive or place and place[0] >= 0):
        return "REJECTED"
    if (score and win and score[0] > 0 and win[0] > 0 and discordant >= 20
        and type(exact) in (int, float) and 0 <= exact < .05
        and (not reactive or place and place[1] <= 0)):
        return "PROMISING"
    return "UNVALIDATED"


def campaign_records(runtime=RUNTIME):
    runtime = pathlib.Path(runtime)
    records, skipped = [], []
    for path in sorted(runtime.glob("*-reactive-summary.json")):
        report = read_json(path)
        if report.get("status") != "complete":
            skipped.append(path.name + ": incomplete/failed")
            continue
        for field, result in report.get("fields", {}).items():
            for label, metrics in result.get("comparisons", {}).items():
                records.append({
                    "campaign": path.name.removesuffix("-reactive-summary.json"),
                    "arm": label, "field": field, "metric_type": "synthetic_reactive",
                    "status": triage(metrics, True), "N": metrics.get("N"),
                    "seed": report.get("config", {}).get("seed"), "source": report.get("sourceSha256"),
                    "metrics": metrics, "evidence": [str(path.resolve())]})
    for path in sorted(runtime.glob("*-screen-summary.json")):
        prefix = path.name.removesuffix("-screen-summary.json")
        config_path = path.with_name(prefix + "-config.json")
        summary = read_json(path)
        config = read_json(config_path) if config_path.is_file() else None
        if not config or set(dict(config.get("arms", []))) != set(summary.get("arms", {})):
            skipped.append(path.name + ": campaign completion not established from config")
            continue
        if any(arm.get("N") != config.get("N") for arm in summary["arms"].values()):
            skipped.append(path.name + ": counts differ from config")
            continue
        analysis_path = path.with_name(prefix + "-analysis.json")
        analysis = read_json(analysis_path) if analysis_path.is_file() else {}
        candidates = [label for label in summary["arms"] if label != "BASE"]
        target = analysis.get("candidateLabel")
        if target is None and len(candidates) == 1:
            target = candidates[0]
        for label in candidates:
            metrics = analysis if target == label else {}
            records.append({
                "campaign": prefix, "arm": label, "field": "historical market",
                "metric_type": "surrogate", "status": triage(metrics),
                "N": summary["arms"][label].get("N"), "seed": summary.get("seed"),
                "source": summary.get("source"),
                "metrics": {**summary["arms"][label], **metrics},
                "evidence": [str(path.resolve())] + ([str(analysis_path.resolve())] if metrics else [])})
    return records, skipped


def one_line(value):
    return str(value).replace("\n", " ").replace("|", "/").strip()


def link(path, workspace):
    path = pathlib.Path(path)
    if not path.is_absolute():
        path = pathlib.Path(workspace) / path
    return f"[{path.name}](<{path}>)"


def render(lessons, campaigns, skipped, workspace=WORKSPACE):
    lines = [MARKER, "# ScrabbleBot persistent learnings", "",
             "The sole live runner must be explicitly confirmed. This learning tool is offline only; no generated decision authorizes deployment.",
             "", "Statuses are research triage: UNVALIDATED needs more evidence; REJECTED describes the tested condition; "
             "PROMISING needs independent confirmation. These labels do not claim live improvement.",
             "", "Intervals are conditional on the simulator and historical inputs. Reused cohorts, multiple comparisons, "
             "optional stopping and CPU timing can invalidate simple interpretations. Joint score/win/placement checks "
             "are conservative triage, not a multiplicity-adjusted guarantee.", "", "## Recorded lessons", ""]
    for lesson in lessons:
        lines += [f"- **{one_line(lesson['status'])}: {one_line(lesson['id'])}** — {one_line(lesson['cause'])}",
                  f"  Action: {one_line(lesson['action'])}",
                  "  Evidence: " + ", ".join(link(p, workspace) for p in lesson["evidence"])]
    if not lessons:
        lines.append("No manual lessons recorded yet.")
    lines += ["", "## Completed campaign evidence", ""]
    for item in campaigns:
        m = item["metrics"]
        reactive = item["metric_type"] == "synthetic_reactive"
        score = m.get("scoreDelta", m.get("pairedScoreDelta"))
        win = m.get("winPPDelta" if reactive else "surrogateDeltaPP")
        lines += [
            f"- **{item['status']} — {one_line(item['campaign'])}/{one_line(item['field'])}/{one_line(item['arm'])}** "
            f"({item['metric_type']}, N={item['N']}, seed={item['seed']})",
            f"  Score delta {score}; conditional 95% interval {m.get('scoreConditional95')}. "
            f"{'Synthetic win' if reactive else 'Historical exceedance'} delta {win} pp; conditional 95% interval "
            f"{m.get('winPPConditional95' if reactive else 'surrogateConditional95')}.",
            f"  Place delta {m.get('placeDelta')}; interval {m.get('placeConditional95')}. "
            f"Discordance gained/lost {m.get('winGained', m.get('exceedanceGainedGames'))}/"
            f"{m.get('winLost', m.get('exceedanceLostGames'))}; exact paired p={m.get('exactDiscordanceP')}.",
            f"  Source: {item['source']}. Evidence: " + ", ".join(link(p, workspace) for p in item["evidence"])]
    if not campaigns:
        lines.append("No completed campaign comparisons available.")
    if skipped:
        lines += ["", "## Excluded incomplete or unverifiable campaigns", ""]
        lines.extend("- " + one_line(reason) for reason in skipped)
    lines += ["", "Generated locally from docs/lessons.jsonl and persistent campaign summaries. "
              "Evidence files remain authoritative; missing confidence fields mean unknown, not zero.", ""]
    return "\n".join(lines)


def refresh(ledger=LEDGER, runtime=RUNTIME, output=OUTPUT, workspace=WORKSPACE):
    output = pathlib.Path(output)
    if output.exists() and not output.read_text().startswith(MARKER):
        raise ValueError("Existing LEARNINGS file is not owned by this generator; refusing to overwrite")
    lessons = read_ledger(ledger)
    campaigns, skipped = campaign_records(runtime)
    content = render(lessons, campaigns, skipped, workspace)
    output.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.NamedTemporaryFile(mode="w", dir=output.parent, prefix=output.name + ".",
                                     suffix=".tmp", delete=False) as handle:
        temp = pathlib.Path(handle.name)
        handle.write(content)
        handle.flush()
        os.fsync(handle.fileno())
    temp.replace(output)
    return {"lessons": len(lessons), "campaignComparisons": len(campaigns),
            "skipped": len(skipped), "output": str(output)}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--lesson", type=pathlib.Path)
    parser.add_argument("--refresh", action="store_true")
    args = parser.parse_args()
    if not args.lesson and not args.refresh:
        parser.error("Supply --lesson FILE, --refresh, or both")
    result = {}
    if args.lesson:
        if args.lesson.stat().st_size > LIMIT:
            raise ValueError("Lesson input exceeds size limit")
        values = json.loads(args.lesson.read_text())
        values = values if isinstance(values, list) else [values]
        if not values:
            raise ValueError("Lesson list must be nonempty")
        for value in values:
            validate_lesson(value)
        result["lessonsInserted"] = sum(append_lesson(value) for value in values)
    if args.refresh:
        result["memory"] = refresh()
    print(json.dumps(result, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
